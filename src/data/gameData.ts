export function computeWeaponStats(weaponId: WeaponId, attachments: LoadoutConfig['attachments']): ComputedWeaponStats {
  const def = WEAPONS[weaponId] || WEAPONS.m4a1;
  const base = { ...def.baseStats, visionBonus: 0, isSuppressed: false, pellets: def.baseStats.pellets ?? 1 };

  (Object.values(attachments) as Array<string | null>).forEach((attId) => {
    if (!attId) return;
    const att = ATTACHMENTS.find((a) => a.id === attId);
    if (!att) return;
    if (att.id === 'muzzle_suppressor') base.isSuppressed = true;
    if (att.statDeltas.damage) base.damage = Math.max(4, base.damage + att.statDeltas.damage);
    if (att.statDeltas.fireRate) base.fireRate = Math.max(0.5, Number((base.fireRate + att.statDeltas.fireRate).toFixed(2)));
    if (att.statDeltas.spread) base.spread = Math.max(0.2, Number((base.spread + att.statDeltas.spread).toFixed(2)));
    if (att.statDeltas.recoil) base.recoil = Math.max(0.2, Number((base.recoil + att.statDeltas.recoil).toFixed(2)));
    if (att.statDeltas.ergonomics) base.ergonomics = Math.max(15, Math.min(100, base.ergonomics + att.statDeltas.ergonomics));
    if (att.statDeltas.range) base.range = Math.max(200, base.range + att.statDeltas.range);
    if (att.statDeltas.magSize) base.magSize = Math.max(3, base.magSize + att.statDeltas.magSize);
    if (att.statDeltas.noiseRadius) base.noiseRadius = Math.max(180, base.noiseRadius + att.statDeltas.noiseRadius);
    if (att.statDeltas.moveSpeedMod) base.moveSpeedMod = Math.max(0.65, Number((base.moveSpeedMod + att.statDeltas.moveSpeedMod).toFixed(2)));
    if (att.statDeltas.visionBonus) base.visionBonus += att.statDeltas.visionBonus;
  });

  // Ergonomics improves reload handling speed smoothly
  const ergoFactor = 1 - (base.ergonomics - 60) * 0.003;
  base.reloadTime = Math.max(0.85, Number((base.reloadTime * ergoFactor).toFixed(2)));

  return base;
}

export function rollLootItem(
  highValueBias: number,
  containerKind?: ContainerSpawnDef['kind']
): LootInstance {
  // Weapon crates and supply boxes prioritize firearm maintenance & repair parts
  const partChance =
    containerKind === 'weapon_crate'
      ? 0.46
      : containerKind === 'supply_box'
        ? 0.28
        : containerKind === 'safe'
          ? 0.14
          : 0;

  if (partChance > 0 && Math.random() < partChance) {
    const partPool = LOOT_TEMPLATES.filter((t) => t.category === 'weapon_part');
    const roll = Math.random();
    let picked = partPool[0];
    if (roll < 0.14 + highValueBias * 0.22) {
      picked = partPool.find((p) => p.templateId === 'cnc_bolt_carrier') || picked;
    } else if (roll < 0.56) {
      const rares = partPool.filter((p) => p.rarity === 'rare');
      picked = rares[Math.floor(Math.random() * rares.length)] || picked;
    } else {
      picked = partPool.find((p) => p.templateId === 'gun_oil_kit') || picked;
    }
    return {
      uid: `loot_${Date.now()}_${Math.random().toString(36).slice(2, 8)}`,
      templateId: picked.templateId,
      name: picked.name,
      rarity: picked.rarity,
      category: picked.category,
      value: picked.value,
      weight: picked.weight,
      revealed: false,
    };
  }

  const r = Math.random();
  let rarity: LootInstance['rarity'] = 'common';
  const legendThresh = 0.015 + highValueBias * 0.14;
  const epicThresh = legendThresh + 0.06 + highValueBias * 0.24;
  const rareThresh = epicThresh + 0.18 + highValueBias * 0.25;
  const uncommonThresh = rareThresh + 0.34;

  if (r < legendThresh) rarity = 'legendary';
  else if (r < epicThresh) rarity = 'epic';
  else if (r < rareThresh) rarity = 'rare';
  else if (r < uncommonThresh) rarity = 'uncommon';

  const pool = LOOT_TEMPLATES.filter((t) => t.rarity === rarity && t.templateId !== 'saeed_blade');
  const picked = pool[Math.floor(Math.random() * pool.length)] || LOOT_TEMPLATES[0];

  return {
    uid: `loot_${Date.now()}_${Math.random().toString(36).slice(2, 8)}`,
    templateId: picked.templateId,
    name: picked.name,
    rarity: picked.rarity,
    category: picked.category,
    value: picked.value,
    weight: picked.weight,
    revealed: false,
  };
}

