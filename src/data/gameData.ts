export function formatCreditsDisplay(credits: number): string {
  if (credits >= 100_000_000) {
    const yi = credits / 100_000_000;
    const formatted = Number.isInteger(yi)
      ? yi.toLocaleString('en-US')
      : yi.toLocaleString('en-US', { maximumFractionDigits: 2 });
    return `${formatted}亿`;
  }
  return credits.toLocaleString('en-US');
}

