export interface WeaponJamRiskInfo {
  level: 'optimal' | 'worn' | 'damaged' | 'critical';
  label: string;
  shortStatus: string;
  jamProbPerShotPct: number;
  color: string;
}

export function getWeaponJamRiskInfo(durability: number): WeaponJamRiskInfo {
  const d = Math.max(0, Math.min(100, durability));
  if (d >= 80) {
    return {
      level: 'optimal',
      label: '工况极佳 · 零卡壳风险',
      shortStatus: '良好',
      jamProbPerShotPct: 0,
      color: '#00E59B',
    };
  }
  if (d >= 55) {
    const pct = Number((1.5 + ((80 - d) / 25) * 3.0).toFixed(1));
    return {
      level: 'worn',
      label: '轻度积碳 · 偶发供弹卡壳',
      shortStatus: '磨损',
      jamProbPerShotPct: pct,
      color: '#F59E0B',
    };
  }
  if (d >= 25) {
    const pct = Number((4.5 + ((55 - d) / 30) * 8.5).toFixed(1));
    return {
      level: 'damaged',
      label: '机构受损 · 高频卡壳隐患',
      shortStatus: '易卡壳',
      jamProbPerShotPct: pct,
      color: '#FB923C',
    };
  }
  const pct = Number((13.0 + ((25 - d) / 25) * 16.0).toFixed(1));
  return {
    level: 'critical',
    label: '严重磨损 · 极易卡壳停射',
    shortStatus: '危急',
    jamProbPerShotPct: pct,
    color: '#F43F5E',
  };
}

