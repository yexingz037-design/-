export function formatWeightKg(weight: number): string {
  const w = Math.max(0, weight);
  return Number.isInteger(w) ? `${w.toFixed(1)} kg` : `${Number(w.toFixed(2))} kg`;
}

// Encumbrance slowdown from carried loot (every 1 kg slows movement by 2.4%, max 45% penalty)
export function computeEncumbrancePenalty(carriedWeightKg: number): number {
  if (carriedWeightKg <= 0) return 0;
  return Math.min(0.45, Number((carriedWeightKg * 0.024).toFixed(3)));
}

